import { test, expect } from "@playwright/test";
import { randomUUID } from "node:crypto";
import { withCanonicalCanvasSnapshot } from "../../app/utils/canonicalCanvasProject";
import { openWorkspaceTool } from "./helpers/workspaceNavigation";

test("classification saves and reloads without losing the legacy program, supports undo and rejects malformed writes", async ({ page, context, request }) => {
  const api = process.env.PLAYWRIGHT_API_BASE_URL ?? "";
  test.skip(process.env.CIVORA_PHASE0_LOCAL_TESTS !== "1" || !/^http:\/\/(127\.0\.0\.1|localhost):/.test(api), "Disposable local accounts only.");
  const registered = await request.post(`${api}/api/auth/register`, { data: { email: `classify-${randomUUID()}@example.test`, password: "Disposable-123", name: "Classification audit" } });
  expect(registered.status()).toBe(200);
  const { token } = await registered.json(), headers = { Authorization: `Bearer ${token}` };
  const input = withCanonicalCanvasSnapshot({ manual_fields: { units: "ft", setback: 20, lot: { x: 0, y: 0, w: 435.6, h: 100 }, site_plan: { building_program_sf: 28000, building_type: "office" }, site_objects: [{ id: "site", name: "Boundary", type: "site", x: 0, y: 0, w: 435.6, d: 100, placed: true }] } });
  const created = await request.post(`${api}/api/projects`, { headers, data: { name: "Classification saved project", project_input: input } });
  expect(created.status()).toBe(200);
  const project = (await created.json()).project;
  const fetch = async () => (await (await request.get(`${api}/api/projects/${project.project_id}`, { headers })).json()).project;
  await context.addInitScript(value => { localStorage.setItem("civora-ai-token", value); sessionStorage.setItem("civora-ai-session-auth-restore", "1"); }, token);
  await page.goto("/");
  await page.getByTestId("header-projects-button").click();
  await page.getByRole("button", { name: "Open project Classification saved project", exact: true }).click();
  await openWorkspaceTool(page, "Setup");
  const row = page.getByTestId("active-brief-summary").getByTestId("brief-value-setbacks");
  await expect(row).toContainText("20 ft");
  await row.locator("summary").click();
  await row.getByRole("combobox", { name: "Setbacks requirement" }).selectOption("required");
  await expect.poll(async () => (await fetch()).project_input.meta.site_inputs.active_brief_classifications_v1?.fields?.setbacks?.priority).toBe("required");
  await row.getByRole("button", { name: "Confirm this value" }).click();
  await expect.poll(async () => (await fetch()).project_input.meta.site_inputs.active_brief_classifications_v1?.fields?.setbacks?.trust).toBe("user_confirmed");
  expect((await fetch()).project_input.manual_fields.site_plan.building_program_sf).toBe(28000);
  await page.reload();
  await expect(page.getByTestId("workspace-canvas-shell")).toBeVisible();
  await expect(page.getByTestId("workspace-stage-brief")).toBeVisible();
  await openWorkspaceTool(page, "Setup");
  await expect(row.getByTestId("brief-trust")).toContainText("user confirmed");
  await row.locator("summary").click();
  await expect(row.getByRole("combobox", { name: "Setbacks requirement" })).toHaveValue("required");
  await page.getByRole("button", { name: "Undo last draft change", exact: true }).click();
  await expect(row.getByTestId("brief-trust")).toContainText("unverified");
  await expect.poll(async () => (await fetch()).project_input.meta.site_inputs.active_brief_classifications_v1?.fields?.setbacks?.trust).toBe("unverified");
  await page.getByRole("button", { name: "Redo draft change", exact: true }).click();
  await expect(row.getByTestId("brief-trust")).toContainText("user confirmed");
  await expect.poll(async () => (await fetch()).project_input.meta.site_inputs.active_brief_classifications_v1?.fields?.setbacks?.trust).toBe("user_confirmed");
  const beforeBad = await fetch();
  const malformed = structuredClone(beforeBad.project_input);
  malformed.meta.site_inputs.active_brief_classifications_v1.fields.setbacks.priority = "invented";
  const rejected = await request.post(`${api}/api/projects`, { headers, data: { project_id: project.project_id, name: project.name, project_input: malformed } });
  expect(rejected.status()).toBeGreaterThanOrEqual(400);
  expect(rejected.status()).toBeLessThan(500);
  expect((await fetch()).revision_token).toBe(beforeBad.revision_token);
  let failedSaves = 0;
  await page.route(`${api}/api/projects`, async route => {
    if (route.request().method() === "POST") { failedSaves++; await route.fulfill({ status: 503, json: { detail: "Synthetic save failure" } }); }
    else await route.continue();
  });
  await row.getByRole("combobox", { name: "Setbacks requirement" }).selectOption("preferred");
  await expect.poll(() => failedSaves).toBeGreaterThan(0);
  await expect(page.getByTestId("header-save-status")).toContainText("Save failed");
  await expect(row.getByRole("combobox", { name: "Setbacks requirement" })).toHaveValue("preferred");
  expect((await fetch()).project_input.meta.site_inputs.active_brief_classifications_v1.fields.setbacks.priority).toBe("required");
  await page.unroute(`${api}/api/projects`);
  await row.getByRole("combobox", { name: "Setbacks requirement" }).selectOption("required");
  await row.getByRole("combobox", { name: "Setbacks requirement" }).selectOption("preferred");
  await expect.poll(async () => (await fetch()).project_input.meta.site_inputs.active_brief_classifications_v1.fields.setbacks.priority).toBe("preferred");
});

test("shared viewers can read brief classifications but cannot edit them", async ({ page, context, request }) => {
  const api = process.env.PLAYWRIGHT_API_BASE_URL ?? "";
  test.skip(process.env.CIVORA_PHASE0_LOCAL_TESTS !== "1" || !/^http:\/\/(127\.0\.0\.1|localhost):/.test(api), "Disposable local accounts only.");
  const register = async (name: string) => {
    const response = await request.post(`${api}/api/auth/register`, { data: { email: `brief-role-${randomUUID()}@example.test`, password: "Disposable-123", name } });
    expect(response.status()).toBe(200); return response.json();
  };
  const owner = await register("Owner"), viewer = await register("Viewer"), headers = { Authorization: `Bearer ${owner.token}` };
  const input = withCanonicalCanvasSnapshot({ manual_fields: { units: "ft", setback: 20, lot: { x: 0, y: 0, w: 435.6, h: 100 } } });
  const created = await request.post(`${api}/api/projects`, { headers, data: { name: "Viewer brief", project_input: input } });
  expect(created.status()).toBe(200); const project = (await created.json()).project;
  const invite = await request.post(`${api}/api/projects/${project.project_id}/admin/invites`, { headers, data: { email: viewer.user.email, role: "viewer" } });
  expect(invite.status()).toBe(200);
  await context.addInitScript(value => { localStorage.setItem("civora-ai-token", value); sessionStorage.setItem("civora-ai-session-auth-restore", "1"); }, viewer.token);
  await page.goto("/");
  await page.getByTestId("header-projects-button").click();
  await page.getByRole("button", { name: "Open project Viewer brief", exact: true }).click();
  await expect(page.getByTestId("project-status-summary")).toContainText("Project opened");
  await openWorkspaceTool(page, "Setup");
  const row = page.getByTestId("active-brief-summary").getByTestId("brief-value-setbacks");
  await expect(row).toContainText("20 ft"); await row.locator("summary").click();
  await expect(row.getByRole("combobox")).toHaveCount(0);
  const summary = page.getByTestId("active-brief-summary");
  await summary.locator("summary").filter({ hasText: "All requirements" }).click();
  await expect(summary.getByRole("button", { name: /^Edit / })).toHaveCount(0);
  const sources = page.getByTestId("brief-source-register");
  await sources.locator("summary").first().click();
  await expect(sources.getByRole("button", { name: "Add source", exact: true })).toHaveCount(0);
  const exportDenied = await request.post(`${api}/api/jobs/export/current-geometry`, { headers: { Authorization: `Bearer ${viewer.token}` }, data: { project_id: project.project_id, expected_revision: project.revision_token, export_format: "pdf", acknowledgement: true } });
  expect([403, 404]).toContain(exportDenied.status());
  const denied = await request.post(`${api}/api/projects`, { headers: { Authorization: `Bearer ${viewer.token}` }, data: { project_id: project.project_id, name: project.name, project_input: { ...input, meta: { site_inputs: { active_brief_classifications_v1: { version: 1, fields: { setbacks: { priority: "required", trust: "unverified", value_key: "test" } } } } } } } });
  expect([403, 404]).toContain(denied.status());
  const unchanged = (await (await request.get(`${api}/api/projects/${project.project_id}`, { headers })).json()).project;
  expect(unchanged.revision_token).toBe(project.revision_token);
});
