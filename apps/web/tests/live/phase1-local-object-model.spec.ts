import { openWorkspaceTool } from "./helpers/workspaceNavigation";
import {expect,test,type Page} from "@playwright/test";
import {randomUUID} from "node:crypto";
import {withCanonicalCanvasSnapshot} from "../../app/utils/canonicalCanvasProject";
const api=process.env.PLAYWRIGHT_API_BASE_URL??"";
const local=process.env.CIVORA_PHASE0_LOCAL_TESTS==="1" && /^http:\/\/(127\.0\.0\.1|localhost):\d+$/.test(api);
test.beforeEach(()=>test.skip(!local,"Disposable local accounts only."));
async function draw(page:Page) {
  await openWorkspaceTool(page, "Draw");
  const panel=page.getByTestId("object-manager-panel");
  if (!(await panel.evaluate(element=>element.hasAttribute("open")))) await panel.locator("summary").click();
}
async function inspect(page:Page,name:string) {
  await draw(page);
  const row=page.getByTestId("object-manager-row").filter({hasText:name}).first();
  await row.getByTestId("object-manager-select").click();
  await row.getByTestId("object-manager-inspect").click();
  await expect(page.getByTestId("object-classification")).toBeVisible();
}

test("website classifies an open outline, saves it as invalid, closes it and reopens a custom type",async({page,request},testInfo)=>{
  const auth=await (await request.post(`${api}/api/auth/register`,{data:{email:`objects-${randomUUID()}@example.test`,password:"Disposable-object-123",name:"Object fixture"}})).json();
  const headers={Authorization:`Bearer ${auth.token}`};
  const created=await request.post(`${api}/api/projects`,{headers,data:{name:"Object model fixture",project_input:withCanonicalCanvasSnapshot({input_mode:"user",manual_fields:{units:"ft",project_name:"Object model fixture",lot:{x:0,y:0,w:900,h:700},site_objects:[{id:"outline",label:"Draft outline",type:"custom",x:100,y:100,w:100,d:100,placed:true,source:"manual_drawn",geometry_type:"polyline",geometry:[[100,100],[200,100],[200,200]]}]}})}});
  expect(created.status()).toBe(200);
  const {project}=await created.json();
  const snapshot=async()=> (await (await request.get(`${api}/api/projects/${project.project_id}`,{headers})).json()).project.project_input;
  const object=async()=> (await snapshot()).manual_fields.site_objects.find((item:{id:string})=>item.id==="outline");
  await page.addInitScript(token=>{sessionStorage.setItem("civora-ai-token",token);sessionStorage.setItem("civora-ai-session-auth-restore","1");},auth.token);
  await page.goto("/");
  await page.getByTestId("header-projects-button").click();
  await page.getByRole("button",{name:"Open project Object model fixture"}).click();
  await inspect(page,"Draft outline");
  await page.getByLabel("Selected object type",{exact:true}).selectOption("building");
  await expect(page.getByTestId("object-classification")).toContainText("Affected calculations paused");
  await expect.poll(async()=> (await object()).type).toBe("building");
  const invalid=await snapshot();
  expect(invalid.canonical_project_v1.buildings[0].object_v1.validation.status).toBe("invalid");
  expect(invalid.canonical_project_v1.buildings[0].object_v1.created_by.actor_id).toBe(auth.user.user_id);
  const blocked=await request.post(`${api}/api/orchestrate`,{headers,data:invalid});
  expect(blocked.status()).toBe(422);
  await page.getByRole("button",{name:"Close outline",exact:true}).click();
  await expect.poll(async()=> (await object()).geometry_type).toBe("polygon");
  await page.getByLabel("Selected object type",{exact:true}).selectOption("new");
  await page.getByLabel("Custom type name").fill("Inspection marker");
  await page.getByRole("button",{name:"Add field",exact:true}).click();
  await page.getByLabel("Field 1 name").fill("Diameter");
  await page.getByLabel("Field 1 kind").selectOption("number");
  await page.getByLabel("Custom type reuse scope").selectOption("account");
  await page.getByRole("button",{name:"Save type",exact:true}).click();
  await expect(page.getByLabel("Object property Diameter")).toBeVisible();
  await page.getByLabel("Object property Diameter").fill("12");
  await expect.poll(async()=> (await object()).meta.custom_properties_v1).toEqual({Diameter:12});
  const library=await (await request.get(`${api}/api/object-types`,{headers})).json();
  expect(library.types[0].name).toBe("Inspection marker");
  await page.reload();
  await inspect(page,"Draft outline");
  await expect(page.getByLabel("Object property Diameter")).toHaveValue("12");
  await expect(page.getByLabel("Selected object type",{exact:true})).toHaveValue(library.types[0].id);
  await page.getByTestId("object-classification").scrollIntoViewIfNeeded();
  await page.screenshot({path:testInfo.outputPath("custom-object-reopened.png")});
  const second=await request.post(`${api}/api/projects`,{headers,data:{name:"Reusable type fixture",project_input:withCanonicalCanvasSnapshot({manual_fields:{units:"ft",site_objects:[{id:"new-object",label:"New object",type:"custom",x:100,y:100,w:20,d:20}]}})}});
  expect(second.status()).toBe(200);
  await page.getByTestId("header-projects-button").click();
  await page.getByRole("button",{name:"Open project Reusable type fixture"}).click();
  await inspect(page,"New object");
  await expect(page.getByLabel("Selected object type",{exact:true}).locator(`option[value="${library.types[0].id}"]`)).toHaveCount(1);
  await page.getByLabel("Selected object type",{exact:true}).selectOption(library.types[0].id);
  await expect(page.getByLabel("Object property Diameter")).toBeVisible();
});

test("website groups separate objects, moves members, undoes redoes and ungroups",async({page,request})=>{
  const auth=await (await request.post(`${api}/api/auth/register`,{data:{email:`groups-${randomUUID()}@example.test`,password:"Disposable-object-123",name:"Group fixture"}})).json();
  const headers={Authorization:`Bearer ${auth.token}`};
  const created=await request.post(`${api}/api/projects`,{headers,data:{name:"Group model fixture",project_input:withCanonicalCanvasSnapshot({input_mode:"user",manual_fields:{units:"ft",project_name:"Group model fixture",lot:{x:0,y:0,w:900,h:700},site_objects:[{id:"one",label:"First member",type:"building",x:100,y:100,w:100,d:100,placed:true,source:"manual_drawn"},{id:"two",label:"Second member",type:"building",x:300,y:100,w:100,d:100,placed:true,source:"manual_drawn"}]}})}});
  expect(created.status()).toBe(200);
  const {project}=await created.json();
  const objects=async()=> (await (await request.get(`${api}/api/projects/${project.project_id}`,{headers})).json()).project.project_input.manual_fields.site_objects;
  await page.addInitScript(token=>{sessionStorage.setItem("civora-ai-token",token);sessionStorage.setItem("civora-ai-session-auth-restore","1");},auth.token);
  await page.goto("/"); await page.getByTestId("header-projects-button").click();
  await page.getByRole("button",{name:"Open project Group model fixture"}).click(); await draw(page);
  for (const label of ["First member","Second member"]) await page.getByTestId("object-manager-row").filter({hasText:label}).getByTestId("object-manager-bulk-select").check();
  await page.getByTestId("object-manager-combine-name").fill("Pilot group");
  await page.getByTestId("object-manager-group-action").click();
  await expect.poll(async()=> (await objects()).filter((item:{type:string})=>item.type==="group").length).toBe(1);
  await inspect(page,"Pilot group");
  await page.getByTestId("selected-object-hide-toggle").click();
  await expect.poll(async()=> (await objects()).filter((item:{meta?:{ui_hidden?:boolean}})=>item.meta?.ui_hidden).length).toBe(3);
  await page.getByTestId("selected-object-hide-toggle").click();
  await expect.poll(async()=> (await objects()).filter((item:{meta?:{ui_hidden?:boolean}})=>item.meta?.ui_hidden).length).toBe(0);
  await page.getByTestId("selected-object-x-input").fill("125");
  await expect.poll(async()=> (await objects()).find((item:{id:string})=>item.id==="two").x).toBe(325);
  expect((await objects()).filter((item:{meta?:{ui_hidden?:boolean}})=>item.meta?.ui_hidden)).toHaveLength(0);
  await page.getByRole("button",{name:"Undo last draft change",exact:true}).click();
  await expect.poll(async()=> (await objects()).find((item:{id:string})=>item.id==="two").x).toBe(300);
  await page.getByRole("button",{name:"Redo draft change",exact:true}).click();
  await expect.poll(async()=> (await objects()).find((item:{id:string})=>item.id==="two").x).toBe(325);
  await draw(page);
  await page.getByTestId("object-manager-combine-name").fill("Outer group");
  await page.getByTestId("object-manager-group-action").click();
  await expect.poll(async()=> (await objects()).filter((item:{type:string})=>item.type==="group").length).toBe(2);
  await inspect(page,"Outer group");
  await page.getByTestId("selected-object-x-input").fill("145");
  await expect.poll(async()=> (await objects()).find((item:{id:string})=>item.id==="two").x).toBe(345);
  await draw(page);
  await page.getByTestId("object-manager-row").filter({hasText:"Outer group"}).getByTestId("object-manager-explode-combined").click();
  await expect.poll(async()=> (await objects()).filter((item:{type:string})=>item.type==="group").length).toBe(1);
  await draw(page);
  await page.getByTestId("object-manager-row").filter({hasText:"Pilot group"}).getByTestId("object-manager-explode-combined").click();
  await expect.poll(async()=> (await objects()).filter((item:{type:string})=>item.type==="group").length).toBe(0);
  expect((await objects()).find((item:{id:string})=>item.id==="two").meta.group_id).toBeNull();
});

test("website combines open lines without forced closure and uncombines the edited outline",async({page,request})=>{
  const auth=await (await request.post(`${api}/api/auth/register`,{data:{email:`lines-${randomUUID()}@example.test`,password:"Disposable-object-123",name:"Line fixture"}})).json();
  const headers={Authorization:`Bearer ${auth.token}`};
  const points:Array<[number,number]>=[[100,100],[200,100],[200,200],[100,200]];
  const lines=points.slice(1).map((end,index)=>({id:`line-${index}`,label:`Edge ${index+1}`,type:"custom",x:Math.min(points[index][0],end[0]),y:Math.min(points[index][1],end[1]),w:Math.max(1,Math.abs(end[0]-points[index][0])),d:Math.max(1,Math.abs(end[1]-points[index][1])),placed:true,source:"manual_drawn",geometry_type:"polyline" as const,geometry:[points[index],end]}));
  const created=await request.post(`${api}/api/projects`,{headers,data:{name:"Line model fixture",project_input:withCanonicalCanvasSnapshot({input_mode:"user",manual_fields:{units:"ft",project_name:"Line model fixture",lot:{x:0,y:0,w:900,h:700},site_objects:lines}})}});
  expect(created.status()).toBe(200); const {project}=await created.json();
  const objects=async()=> (await (await request.get(`${api}/api/projects/${project.project_id}`,{headers})).json()).project.project_input.manual_fields.site_objects;
  await page.addInitScript(token=>{sessionStorage.setItem("civora-ai-token",token);sessionStorage.setItem("civora-ai-session-auth-restore","1");},auth.token);
  await page.goto("/");await page.getByTestId("header-projects-button").click();await page.getByRole("button",{name:"Open project Line model fixture"}).click();await draw(page);
  for (const label of ["Edge 1","Edge 2","Edge 3"]) await page.getByTestId("object-manager-row").filter({hasText:label}).getByTestId("object-manager-bulk-select").check();
  await page.getByTestId("object-manager-combine-name").fill("Combined outline");
  await page.getByTestId("object-manager-combine-type").selectOption("building");
  page.once("dialog",dialog=>void dialog.dismiss());
  await page.getByTestId("object-manager-combine-action").click();
  await expect.poll(async()=> (await objects()).find((item:{label:string})=>item.label==="Combined outline")?.geometry_type).toBe("polyline");
  await inspect(page,"Combined outline");
  await expect(page.getByTestId("object-classification")).toContainText("Affected calculations paused");
  await page.getByRole("button",{name:"Close outline",exact:true}).click();
  await page.getByTestId("selected-object-vertex-insert").first().click();
  await expect.poll(async()=> (await objects()).find((item:{label:string})=>item.label==="Combined outline").geometry.length).toBe(5);
  await draw(page);
  await page.getByTestId("object-manager-row").filter({hasText:"Combined outline"}).getByTestId("object-manager-explode-combined").click();
  await expect.poll(async()=> (await objects()).filter((item:{meta?:{ui_hidden?:boolean}})=>!item.meta?.ui_hidden).length).toBe(5);
  await page.getByRole("button",{name:"Undo last draft change",exact:true}).click();
  await expect.poll(async()=> (await objects()).filter((item:{label:string})=>item.label==="Combined outline").length).toBe(1);
  await page.getByRole("button",{name:"Redo draft change",exact:true}).click();
  await expect.poll(async()=> (await objects()).length).toBe(5);
});
